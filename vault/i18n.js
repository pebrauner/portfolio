/* =====================================================================
   The Vault — i18n engine + translation catalogs.
   Plain classic script (NO modules) loaded BEFORE decks.js / app.js so the
   global `tr()` and `I18N` are visible to every later classic script and to
   the standalone pages (share/d/s/u).

   GOLDEN RULE: tr() wraps the human-VISIBLE label only. Never pass internal
   keys, data-* attribute values, condition/rarity/colour codes, history
   types, view tokens, or anything persisted in state through tr(). Card
   names / type lines / oracle text are Scryfall data and stay English.

   Catalog shape: I18N.dicts.<lang> = { "<English source>": "<translation>" }.
   English is the source language: a missing entry falls back to the key
   itself, so untranslated strings simply stay English. A "|context" suffix
   on a key (e.g. tr('All|hist')) disambiguates identical English words that
   need different translations; the suffix is stripped for the fallback.
   ===================================================================== */
'use strict';

const I18N = {
  lang: 'en',
  dicts: { es: {} },   // populated at the bottom of this file

  dict() { return this.lang === 'en' ? null : (this.dicts[this.lang] || null); },
  locale() { return this.lang === 'en' ? undefined : this.lang; },   // for toLocaleDateString(locale, …)

  /* translate a source string (optionally interpolating {name} params) */
  t(key, params) {
    if (key == null) return key;
    let s = String(key);
    const d = this.dict();
    let out = (d && Object.prototype.hasOwnProperty.call(d, s)) ? d[s] : null;
    if (out == null) {                       // no translation → English fallback (strip |context)
      const bar = s.indexOf('|');
      out = bar >= 0 ? s.slice(0, bar) : s;
    }
    if (params) out = out.replace(/\{(\w+)\}/g, (m, k) => (params[k] != null ? String(params[k]) : m));
    return out;
  },

  /* apply translations to static markup under `root`.
     [data-i18n]="src"        → textContent
     [data-i18n-html]="src"   → innerHTML (for labels that contain markup)
     [data-i18n-ph]="src"     → placeholder
     [data-i18n-title]="src"  → title
     [data-i18n-aria]="src"   → aria-label
     The English source lives in the attribute, so switching back to EN is a
     no-op restore (t() returns the key) — no caching needed. */
  apply(root) {
    root = root || document;
    const self = this;
    root.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = self.t(el.getAttribute('data-i18n')); });
    root.querySelectorAll('[data-i18n-html]').forEach(el => { el.innerHTML = self.t(el.getAttribute('data-i18n-html')); });
    root.querySelectorAll('[data-i18n-ph]').forEach(el => { el.setAttribute('placeholder', self.t(el.getAttribute('data-i18n-ph'))); });
    root.querySelectorAll('[data-i18n-title]').forEach(el => { el.setAttribute('title', self.t(el.getAttribute('data-i18n-title'))); });
    root.querySelectorAll('[data-i18n-aria]').forEach(el => { el.setAttribute('aria-label', self.t(el.getAttribute('data-i18n-aria'))); });
  },

  /* switch language + repaint static markup. Persistence / dynamic re-render
     are the caller's job (app.js does state.prefs.lang = …; save(); render()). */
  setLang(lang) {
    this.lang = (lang === 'es') ? 'es' : 'en';
    try { document.documentElement.lang = this.lang; } catch (e) {}
    this.apply(document);
  },

  /* best language for a standalone/public page with no app state of its own:
     ?lang= URL param → the viewer's own stored Vault pref → browser → en */
  detect() {
    try { const u = new URLSearchParams(location.search).get('lang'); if (u === 'es' || u === 'en') return u; } catch (e) {}
    try { const raw = localStorage.getItem('mtg-vault-v1'); if (raw) { const p = JSON.parse(raw).prefs; if (p && (p.lang === 'es' || p.lang === 'en')) return p.lang; } } catch (e) {}
    try { if ((navigator.language || '').toLowerCase().startsWith('es')) return 'es'; } catch (e) {}
    return 'en';
  },
};

/* Short global alias used everywhere. NOT named t() — app.js uses `t` as a
   local iterator/param in many places, which would shadow a global t. */
function tr(key, params) { return I18N.t(key, params); }

